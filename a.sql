IF DB_ID ('QL_GIAOHANG') IS NOT NULL
DROP DATABASE QL_GIAOHANG;

GO CREATE DATABASE QL_GIAOHANG;

GO USE QL_GIAOHANG;

GO
CREATE TABLE
    NHACUNGCAP (
        MaNCC CHAR(10) NOT NULL PRIMARY KEY,
        TenNCC NVARCHAR (100) NOT NULL,
        DiaChi NVARCHAR (200),
        DienThoai VARCHAR(15) UNIQUE,
        Email VARCHAR(50) UNIQUE
    );

GO
CREATE TABLE
    LOAIHANG (
        MaLoaiHang CHAR(10) NOT NULL PRIMARY KEY,
        TenLoaiHang NVARCHAR (100) NOT NULL
    );

GO
CREATE TABLE
    MATHANG (
        MaMH CHAR(10) NOT NULL PRIMARY KEY,
        TenMH NVARCHAR (100) NOT NULL,
        DonViTinh NVARCHAR (20) NOT NULL,
        DonGia DECIMAL(18, 2) CHECK (DonGia >= 0),
        SoLuong INT CHECK (SoLuong >= 0),
        MaNCC CHAR(10),
        MaLoaiHang CHAR(10),
        CONSTRAINT FK_MH_NCC FOREIGN KEY (MaNCC) REFERENCES NHACUNGCAP (MaNCC) ON DELETE CASCADE ON UPDATE CASCADE,
        CONSTRAINT FK_MH_LH FOREIGN KEY (MaLoaiHang) REFERENCES LOAIHANG (MaLoaiHang) ON DELETE CASCADE ON UPDATE CASCADE
    );

